package protocol

import (
	"crypto/rand"
	"fmt"
	"math/big"
	"unicode/utf8"
)

// Случайные ники. Их выдают в двух местах: гостю, который нажал «Играть гостем» и не вводил
// имя вовсе, и аккаунту, которому не досталось имя из профиля Яндекса (занято или не прошло
// проверку). Генератор общий, чтобы имя выглядело одинаково в обоих случаях.
//
// Форма — «прилагательное существительное» в снежной теме: такое имя читается в лобби и в чате
// как имя, а не как идентификатор. Ограничение жёсткое: ник — не длиннее 16 рун вместе с
// пробелом (см. NormalizeNick), поэтому слова короткие, а длины проверяет тест.

// nickAdjectives и nickNouns подобраны так, чтобы любая пара проходила NormalizeNick: только
// буквы, сумма длин со пробелом не больше 16, никакого мата (это тоже проверяет тест).
var nickAdjectives = []string{
	"Ловкий", "Хитрый", "Быстрый", "Смелый", "Бодрый", "Меткий", "Шумный", "Тихий",
	"Дерзкий", "Верный", "Гордый", "Резвый", "Хмурый", "Зимний", "Снежный", "Ледяной",
	"Морозный", "Колючий", "Мохнатый", "Пушистый", "Упрямый", "Сонный", "Весёлый", "Грозный",
	"Могучий", "Юркий", "Вьюжный", "Северный", "Крепкий", "Отважный",
}

var nickNouns = []string{
	"Пингвин", "Морж", "Тюлень", "Песец", "Олень", "Барсук", "Бобр", "Лис",
	"Волк", "Медведь", "Снегирь", "Филин", "Сокол", "Ворон", "Кабан", "Рысь",
	"Хорёк", "Сурок", "Лось", "Як", "Бизон", "Кит", "Нарвал", "Тигр",
	"Ёж", "Заяц", "Барс", "Крот", "Хомяк", "Пёс",
}

// RandomNick возвращает случайное имя вида «Ловкий Пингвин». Оно заведомо проходит
// NormalizeNick, но не проверено на занятость: это дело вызывающего (у гостя и у аккаунта
// разные реестры имён).
func RandomNick() string {
	return nickAdjectives[randIndex(len(nickAdjectives))] + " " + nickNouns[randIndex(len(nickNouns))]
}

// FallbackNick — запасное имя на случай, когда все случайные пары заняты: пространство «Игрок
// NNNN» куда больше комбинаций из двух списков, и упереться в него почти невозможно.
func FallbackNick() string {
	return fmt.Sprintf("Игрок %d", randIndex(10000))
}

// RandomNickTotal — сколько всего разных имён умеет выдать RandomNick. Нужно тем, кто решает,
// сколько попыток подбора имеет смысл делать.
func RandomNickTotal() int { return len(nickAdjectives) * len(nickNouns) }

// MaxNickRunes — предельная длина ника (см. NormalizeNick). Вынесено сюда, потому что списки
// слов обязаны в него укладываться, и тест проверяет это по константе, а не по числу в коде.
const MaxNickRunes = 16

func randIndex(n int) int {
	v, err := rand.Int(rand.Reader, big.NewInt(int64(n)))
	if err != nil {
		panic(err)
	}
	return int(v.Int64())
}

// nickRunes — длина имени в рунах; отдельная функция ради читаемости теста.
func nickRunes(s string) int { return utf8.RuneCountInString(s) }
